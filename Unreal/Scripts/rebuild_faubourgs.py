def district_floor(index, mat, water, materials):
    spans = BANKS[index-1]
    for column, (lo, hi) in enumerate(spans):
        x = -2200+column*400
        tile_deck(mat,x,(lo+hi)*200,400,(hi-lo)*400)
        for side, edge in ((-1,lo*400),(1,hi*400)):
            mesh("Mur de quai", (x,edge,-66), (400,42,132), materials['wall'])
            mesh("Couronnement du quai", (x,edge,6), (400,56,12), materials['edge'],collision=False)
            invisible_wall(x,edge,400,14)
            if column % 2 == 0:
                mesh("Contrefort", (x+154,edge,-34), (56,75,160), materials['wall'],collision=False)
                bollard(x+154,edge-side*42,materials)
        if column:
            before = spans[column-1]
            for edge, previous in zip((lo,hi),before):
                if edge != previous:
                    center = (edge+previous)*200
                    depth = abs(edge-previous)*400
                    mesh("Retour de quai", (x-200,center,-66), (42,depth,132), materials['wall'])
                    mesh("Arête du quai", (x-200,center,6), (56,depth,12), materials['edge'],collision=False)
                    invisible_wall(x-200,center,14,depth)
    for sign, (lo,hi) in ((-1,spans[0]),(1,spans[-1])):
        invisible_wall(sign*2400,(lo+hi)*200,20,(hi-lo)*400)
        mesh("Tête du quai", (sign*2400,(lo+hi)*200,-60), (50,(hi-lo)*400,130), materials['wall'])


def bollard(x,y,materials):
    mesh("Borne en fonte",(x,y,40),(42,42,80),materials['iron'],shape='Cylinder')
    mesh("Chapeau de borne",(x,y,81),(52,52,10),materials['brass'],shape='Cylinder',collision=False)


def building(x,y,width,depth,height,materials,lit=True):
    # Rear façades provide large silhouettes and doorways at a human scale.
    mesh("Bâtiment du faubourg",(x,y,height/2),(width,depth,height),materials['wall'])
    for z in (15,height*.53,height):
        mesh("Corniche de pierre",(x,y-depth/2-8,z),(width+24,24,22),materials['edge'],collision=False)
    for dx in (-width*.43,width*.43):
        mesh("Pilastre",(x+dx,y-depth/2-14,height/2),(34,34,height+25),materials['edge'],collision=False)
    for dx in range(int(-width/2+95),int(width/2-45),160):
        for z in (height*.30,height*.75):
            mesh("Encadrement de fenêtre",(x+dx,y-depth/2-21,z),(91,22,130),materials['iron'],collision=False)
            mesh("Vitre de façade",(x+dx,y-depth/2-34,z),(70,4,105),materials['glass' if lit else 'blueglass'],collision=False)
            mesh("Traverse de fenêtre",(x+dx,y-depth/2-38,z),(74,7,6),materials['iron'],collision=False)
    mesh("Toiture sombre",(x,y,height+28),(width+40,depth+40,56),materials['iron'],collision=False)


